function escapeHtml(value: string) {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;')
}

export type CreateMarkerDivIconOptions = {
  /** Mặc định [40, 44] — cluster có thể truyền rộng hơn để vùng hover/click khớp label bung ra */
  iconSize?: [number, number]
  /** Mặc định tâm đáy marker (giữa đáy khung 40px) */
  iconAnchor?: [number, number]
}

/**
 * HTML/CSS giống `DefaultMarker`: bubble trắng + vòng tròn xanh + nhà + label + tam giác pin.
 *
 * Chỉ trả về options thuần để tránh kéo `leaflet` vào lúc module được evaluate.
 * Việc tạo `divIcon(...)` sẽ diễn ra bên trong client component sau khi Leaflet đã load.
 */
export function createMarkerDivIconOptions(label: string, options?: CreateMarkerDivIconOptions) {
  const iconSize: [number, number] = options?.iconSize ?? [
    MARKER_DIV_ICON_WIDTH,
    MARKER_DIV_ICON_HEIGHT,
  ]
  const iconAnchor: [number, number] = options?.iconAnchor ?? [
    MARKER_DIV_ICON_WIDTH / 2,
    MARKER_DIV_ICON_HEIGHT,
  ]

  return {
    className: 'leaflet-div-icon interactive-map-default-marker-root',
    html:
      '<div class="interactive-map-default-marker">' +
      '<div class="interactive-map-default-marker__bubble">' +
      '<div class="interactive-map-default-marker__circle" aria-hidden="true">' +
      HOUSE_SVG +
      '</div>' +
      `<div class="interactive-map-default-marker__label">${escapeHtml(label)}</div>` +
      '</div>' +
      `<img class="interactive-map-default-marker__pin" src="${MARKER_DATA_URL}" alt="" />` +
      '</div>',
    iconSize,
    iconAnchor,
  }
}
